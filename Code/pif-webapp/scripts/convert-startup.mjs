// Converts the pet's startup picture (the mascot over "JAM" on teal) into a full-screen
// RGB565 image in flash, for the upright 240x320 display:
//   firmware/pet_story_player/startup_image.h
//
// Usage:  node scripts/convert-startup.mjs [picture]   (default assets/pet-startup/startup.png)
// Needs ffmpeg (set FFMPEG=path\to\ffmpeg.exe if it isn't on PATH). The picture is scaled to
// the screen's width and centred, with the teal filling above and below.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const W = 240
const H = 320
const BACKGROUND = '0x4a7a7e' // the teal of the team's design
const input = process.argv[2] ?? 'assets/pet-startup/startup.png'
const ffmpeg = process.env.FFMPEG ?? 'ffmpeg'

const raw = execFileSync(ffmpeg, [
  '-v', 'error',
  '-i', input,
  '-vf', `scale=${W}:-2:flags=lanczos,pad=${W}:${H}:(ow-iw)/2:(oh-ih)/2:color=${BACKGROUND}`,
  '-frames:v', '1',
  '-f', 'rawvideo',
  '-pix_fmt', 'rgb565le',
  '-',
], { maxBuffer: 16 * 1024 * 1024 })

if (raw.length !== W * H * 2) throw new Error(`expected ${W * H * 2} bytes, got ${raw.length}`)

const values = []
for (let i = 0; i < raw.length; i += 2) values.push('0x' + raw.readUInt16LE(i).toString(16).padStart(4, '0'))
const rows = []
for (let i = 0; i < values.length; i += 16) rows.push('  ' + values.slice(i, i + 16).join(', '))

writeFileSync(
  'firmware/pet_story_player/startup_image.h',
  `// Generated by scripts/convert-startup.mjs from ${input.replace(/\\/g, '/')}. Don't edit by hand.
// The startup picture: ${W}x${H} RGB565, row by row, for the upright screen.
#pragma once
#include <pgmspace.h>

#define STARTUP_W ${W}
#define STARTUP_H ${H}
static const uint16_t STARTUP_IMAGE[${W * H}] PROGMEM = {
${rows.join(',\n')}
};
`,
)
console.log(`firmware/pet_story_player/startup_image.h: ${W}x${H}, ${raw.length} bytes`)
